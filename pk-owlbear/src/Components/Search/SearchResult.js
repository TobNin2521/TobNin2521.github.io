    const getCost = (amount) => {
        const denominations = [
            { name: 'pp', value: 1000 }, // Platinum pieces
            { name: 'gp', value: 100 },  // Gold pieces
            { name: 'ep', value: 50 },   // Electrum pieces
            { name: 'sp', value: 10 },   // Silver pieces
            { name: 'cp', value: 1 }     // Copper pieces
        ];
        
        let result = [];
        
        for (let denom of denominations) {
            let count = Math.floor(amount / denom.value);
            if (count > 0) {
                result.push(`${count}${denom.name}`);
                amount %= denom.value;
            }
        }
        
        return result.join(' ');
    };

